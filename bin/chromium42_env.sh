#!/bin/bash
# =============================================================================
# chromium42_env.sh — environment for building Chromium 42 on Android 4.0 (ICS)
# Source this file:  source chromium42_env.sh
# =============================================================================

# --- Where everything lives ---------------------------------------------------
export CHROMIUM_ROOT="${CHROMIUM_ROOT:-$HOME/chromium42}"
export DEPOT_TOOLS_ROOT="${DEPOT_TOOLS_ROOT:-$HOME/build_env/depot_tools}"

# --- The key fix: bypass CIPD/vpython3 bootstrap -----------------------------
# Modern depot_tools tries to download ~15 LUCI infra packages (vpython3,
# luci-auth, reclient, etc.) on every invocation. For Chromium 42 these are
# unnecessary and often fail (timeouts, package not found, etc.) before the
# real sync even starts.
#
# Solution: create stub binaries that pretend to be cipd/vpython3 but just
# invoke the pyenv-installed Python / do nothing.
export DEPOT_TOOLS_BYPASS_BIN="${DEPOT_TOOLS_BYPASS_BIN:-$HOME/build_env/.bypass_bin}"
mkdir -p "$DEPOT_TOOLS_BYPASS_BIN"

# IMPORTANT: Modern depot_tools requires Python 3.9+ (uses `Iterable[str]`
# type hint without import, PEP 585). On Ubuntu 18.04 the system python3 is
# 3.6.9, so we install Python 3.11 via pyenv (see setup_env.sh).
# Deadsnakes PPA NO LONGER SUPPORTS Ubuntu 18.04 bionic — that's why we use
# pyenv which compiles Python from source.
#
# Initialize pyenv if it's installed
export PYENV_ROOT="${PYENV_ROOT:-$HOME/.pyenv}"
if [ -d "$PYENV_ROOT/bin" ]; then
    export PATH="$PYENV_ROOT/bin:$PATH"
    eval "$(pyenv init - 2>/dev/null)" 2>/dev/null || true
fi

# Find a Python 3.x that's >=3.9 (pyenv-shimmed or system)
PYTHON_BIN=""
for v in 3.11 3.10 3.9; do
    # Try pyenv-managed version first
    if [ -x "$PYENV_ROOT/versions/$v/bin/python" ]; then
        PYTHON_BIN="$PYENV_ROOT/versions/$v/bin/python"
        break
    fi
    # Then system-installed
    if command -v "python$v" >/dev/null 2>&1; then
        PYTHON_BIN="$(command -v "python$v")"
        break
    fi
done
# Fallback: hope `python3` is new enough (true on Ubuntu 20.04+)
if [ -z "$PYTHON_BIN" ]; then
    PYTHON_BIN="$(command -v python3)"
fi
echo "Using Python: $PYTHON_BIN ($($PYTHON_BIN --version 2>&1))"

# Stub vpython3: just exec the pinned python version
# (force-regenerate if PYTHON_BIN changed since last run)
cat > "$DEPOT_TOOLS_BYPASS_BIN/vpython3" <<STUB
#!/bin/bash
# Stub: bypass CIPD vpython3 bootstrap (uses pinned Python instead)
# Generated by chromium42_env.sh on \$(date -u +"%Y-%m-%dT%H:%M:%SZ")
exec $PYTHON_BIN "\$@"
STUB
chmod +x "$DEPOT_TOOLS_BYPASS_BIN/vpython3"

# Stub cipd: pretend ensure succeeds (does nothing), Chromium 42 doesn't need
# any CIPD packages from the network
if [ ! -e "$DEPOT_TOOLS_BYPASS_BIN/cipd" ]; then
    cat > "$DEPOT_TOOLS_BYPASS_BIN/cipd" <<'STUB'
#!/bin/bash
# Stub: disables CIPD package downloads (Chromium 42 doesn't need them)
case "$1" in
  ensure)
    # Real cipd ensure downloads manifest packages. We pretend success.
    exit 0
    ;;
  version)
    echo "stub-cipd 1.0 (no network, Chromium 42 build)"
    ;;
  *)
    # Other subcommands (puppet-check, search, etc.) — return success
    exit 0
    ;;
esac
STUB
    chmod +x "$DEPOT_TOOLS_BYPASS_BIN/cipd"
fi

# Bypass dir MUST be first in PATH so our stubs shadow depot_tools' real ones.
# pyenv shims come next so `python3` resolves to pyenv's 3.11 (not system 3.6).
#
# IMPORTANT: We do NOT want depot_tools/ninja wrapper (it requires
# depot_tools bootstrap which downloads CIPD packages). Instead we use
# system ninja-build package. The wrapper function `ninja_run()` below
# invokes /usr/bin/ninja directly, bypassing depot_tools' wrapper.
#
# NOTE: We don't override `ninja` command itself because that creates
# infinite recursion (function calls itself). Use `ninja_run` instead,
# OR call /usr/bin/ninja directly.
export PATH="$DEPOT_TOOLS_BYPASS_BIN:$DEPOT_TOOLS_ROOT:$PYENV_ROOT/shims:$PATH"

# Find system ninja (not depot_tools' wrapper).
# Store as a variable, not a function override (to avoid recursion).
SYS_NINJA=""
for cand in /usr/bin/ninja /usr/local/bin/ninja /opt/ninja/bin/ninja; do
    if [ -x "$cand" ]; then
        SYS_NINJA="$cand"
        break
    fi
done
export SYS_NINJA

# Helper: run system ninja (bypassing depot_tools wrapper)
# Also prepends python2_bin to PATH so subprocess 'python' calls use python2.7
# (ninja invokes many Python 2 scripts: grit.py, mojom_bindings_generator.py,
# java_cpp_enum.py, jinja_template.py, etc.)
# Usage:  ninja_run -C out/Release chrome_shell_apk
ninja_run() {
    if [ -z "$SYS_NINJA" ]; then
        echo "ERROR: ninja not found in /usr/bin or /usr/local/bin"
        echo "  Install:  sudo apt install ninja-build  (Ubuntu/Debian)"
        echo "           sudo pacman -S ninja          (Arch/Manjaro)"
        return 1
    fi
    if ! command -v python2.7 >/dev/null 2>&1; then
        echo "ERROR: python2.7 not installed"
        echo "  Install:  sudo apt install python2.7  (Ubuntu/Debian)"
        echo "           yaourt -S python2            (Arch/Manjaro AUR)"
        return 1
    fi
    # Prepend python2_bin so subprocess 'python' calls use python2.7
    # (Python 2 scripts: grit.py, mojom_bindings_generator.py, etc.)
    # Also keep depot_tools in PATH (for some build tools)
    PATH="$PYTHON2_BYPASS_BIN:$DEPOT_TOOLS_BYPASS_BIN:$DEPOT_TOOLS_ROOT:$PATH" \
        "$SYS_NINJA" "$@"
}

# --- Python 2 wrapper for GYP scripts (Chromium 42 GYP is Python 2) ---------
# GYP scripts in Chromium 42 (build/gyp_chromium, build/util/version.py,
# android_webview/tools/webview_licenses.py, etc.) are Python 2.
# They use `#!/usr/bin/env python` and call subprocess with `python ...`.
# We need `python` to resolve to python2.7 ONLY when running GYP.
#
# Solution: create a separate dir with python → python2.7 symlink.
# The wrapper function below prepends it to PATH just for gyp_chromium.
export PYTHON2_BYPASS_BIN="${PYTHON2_BYPASS_BIN:-$HOME/build_env/.python2_bin}"
if command -v python2.7 >/dev/null 2>&1; then
    mkdir -p "$PYTHON2_BYPASS_BIN"
    if [ ! -e "$PYTHON2_BYPASS_BIN/python" ]; then
        ln -sf "$(command -v python2.7)" "$PYTHON2_BYPASS_BIN/python"
    fi
    if [ ! -e "$PYTHON2_BYPASS_BIN/python2" ]; then
        ln -sf "$(command -v python2.7)" "$PYTHON2_BYPASS_BIN/python2"
    fi
else
    echo ""
    echo "⚠ python2.7 is NOT installed! GYP step will fail."
    echo "  Install it:  sudo apt install python2.7"
fi

# Wrapper function: runs gyp_chromium with python2.7 forced
# Usage:  gyp_chromium [args...]
# Default args if none given: --depth=. --check
gyp_chromium() {
    if [ ! -x "$CHROMIUM_ROOT/src/build/gyp_chromium" ]; then
        echo "ERROR: $CHROMIUM_ROOT/src/build/gyp_chromium not found"
        echo "  Run this from a context where CHROMIUM_ROOT is set"
        return 1
    fi
    if ! command -v python2.7 >/dev/null 2>&1; then
        echo "ERROR: python2.7 not installed. Install: sudo apt install python2.7"
        return 1
    fi
    (
        # Prepend python2_bin so subprocess 'python' calls use python2.7
        # Override pyenv shims temporarily
        export PATH="$PYTHON2_BYPASS_BIN:$DEPOT_TOOLS_BYPASS_BIN:$DEPOT_TOOLS_ROOT:$PATH"
        # Force python2.7 to run gyp_chromium directly
        cd "$CHROMIUM_ROOT/src"
        if [ $# -eq 0 ]; then
            python2.7 build/gyp_chromium --depth=. --check
        else
            python2.7 build/gyp_chromium "$@"
        fi
    )
}

# --- Disable depot_tools auto-update (we want stable behavior) --------------
export DEPOT_TOOLS_UPDATE=0
# Disable analytics
export DEPOT_TOOLS_METRICS=0
# Belt-and-suspenders: also set VPYTHON_BYPASS (some scripts check this var)
export VPYTHON_BYPASS="manually managed python not supported by chrome operations"

# --- Java 8 (OpenJDK 8 from Ubuntu 18.04 repos works for Chromium 42) -------
if command -v javac >/dev/null 2>&1; then
    export JAVA_HOME="$(dirname "$(dirname "$(readlink -f "$(command -v javac)")")")"
fi

# --- GYP build configuration (Chromium 42 uses GYP, NOT GN!) -----------------
# These are read by build/android/envsetup.sh
export GYP_DEFINES="target_arch=arm"
export GYP_DEFINES="${GYP_DEFINES} arm_version=7"
export GYP_DEFINES="${GYP_DEFINES} arm_float_abi=softfp"
export GYP_DEFINES="${GYP_DEFINES} OS=android"
export GYP_DEFINES="${GYP_DEFINES} chromeos=0"
export GYP_DEFINES="${GYP_DEFINES} branding=Chromium"
export GYP_DEFINES="${GYP_DEFINES} buildtype=Official"
# === Proprietary codecs & DRM (enabled per user request) ===
# These add ~4-5 MB to the final APK (vs ~24 MB without, ~31 MB official Chrome 42)
export GYP_DEFINES="${GYP_DEFINES} proprietary_codecs=1"
export GYP_DEFINES="${GYP_DEFINES} ffmpeg_branding=\"Chrome\""
export GYP_DEFINES="${GYP_DEFINES} enable_widevine=1"
export GYP_DEFINES="${GYP_DEFINES} enable_widevine_cdm_host_verification=0"
# === Still disabled: pure Google services ===
export GYP_DEFINES="${GYP_DEFINES} disable_component_updater=1"
export GYP_DEFINES="${GYP_DEFINES} safe_browsing=0"
export GYP_DEFINES="${GYP_DEFINES} enable_google_now=0"
# === Extensions DISABLED ===
# v1: had enable_extensions=1, which pulled in 200+ desktop-only symbols
# (Browser, TabStripModel, BrowserList, etc.) causing link failures.
# Extensions don't work on Android ICS anyway (no Browser window),
# so we disable them entirely to get a working .so.
# export GYP_DEFINES="${GYP_DEFINES} enable_extensions=1"
export GYP_DEFINES="${GYP_DEFINES} enable_extensions=0"
export GYP_DEFINES="${GYP_DEFINES} enable_plugins=1"
# === Disable clang — use system gcc instead ===
# Chromium 42 sets clang=1 on Linux by default, which makes GYP use the
# LLVM/clang from third_party/llvm-build/Release+Asserts/bin/clang++.
# That directory doesn't exist because we skipped the clang update hook.
# Setting clang=0 makes GYP use system g++ for host compilation
# (protoc, v8 snapshots, mojo code generators, etc.)
# Target compilation (ARM) uses NDK's gcc anyway, not clang.
export GYP_DEFINES="${GYP_DEFINES} clang=0"
export GYP_DEFINES="${GYP_DEFINES} host_clang=0"
# === Disable -Werror globally ===
# V8 in Chromium 42 uses Heap as incomplete type in many places (UB).
# On GCC 4.9 (2015) this was a warning. On GCC 7 (Ubuntu 18.04) it's
# still a warning but mksnapshot segfaults at runtime due to UB.
# Setting werror='' disables -Werror for both Chromium and V8 builds.
# This lets the warnings through without failing the build.
export GYP_DEFINES="${GYP_DEFINES} werror=''"
# === Disable V8 snapshot generation ===
# mksnapshot (host binary) segfaults on GCC 7 due to UB in v8/src/objects.h
# (Heap used as incomplete type). Disabling v8_use_snapshot skips mksnapshot
# entirely. V8 will compile JS at startup instead of loading a snapshot.
# Cost: 2-5 seconds slower browser startup on ICS devices.
#
# Must disable BOTH v8_use_snapshot AND v8_use_external_startup_data,
# otherwise GYP still tries to build v8_external_snapshot which needs mksnapshot.
export GYP_DEFINES="${GYP_DEFINES} v8_use_snapshot=0"
export GYP_DEFINES="${GYP_DEFINES} v8_use_external_startup_data=0"
export GYP_GENERATORS="ninja"
export GYP_DEFINES="${GYP_DEFINES} android_sdk_root=$CHROMIUM_ROOT/src/third_party/android_tools/sdk"

# --- Show what we ended up with ----------------------------------------------
echo "==================================================================="
echo " Chromium 42 build environment"
echo "==================================================================="
echo " CHROMIUM_ROOT       = $CHROMIUM_ROOT"
echo " DEPOT_TOOLS_ROOT    = $DEPOT_TOOLS_ROOT"
echo " BYPASS_BIN          = $DEPOT_TOOLS_BYPASS_BIN (cipd/vpython3 stubs)"
echo " JAVA_HOME           = ${JAVA_HOME:-<not set>}"
echo ""
echo " Python versions:"
echo "   pyenv root         = ${PYENV_ROOT}"
echo "   pyenv versions     = $(pyenv versions 2>/dev/null | tr '\n' ' ')"
echo "   python3.11 (pyenv) = $(test -x $PYENV_ROOT/versions/3.11/bin/python && $PYENV_ROOT/versions/3.11/bin/python --version 2>&1 || echo 'not installed (run bin/setup_env.sh)')"
echo "   python3            = $(command -v python3 2>/dev/null) → $(python3 --version 2>&1)"
echo "   python2.7          = $(command -v python2.7 2>/dev/null || echo 'NOT INSTALLED (sudo apt install python2.7)')"
echo "   python (gyp wrapper) = $PYTHON2_BYPASS_BIN/python"
echo ""
echo "   python3 must be ≥3.9 for modern depot_tools."
echo "   python2.7 needed for Chromium 42 GYP scripts (build/gyp_chromium)."
echo ""
echo " javac               = $(command -v javac 2>/dev/null)"
echo " git                 = $(git --version 2>&1)"
echo " gclient             = $(command -v gclient 2>/dev/null)"
echo " cipd (stub)         = $(command -v cipd 2>/dev/null)"
echo " vpython3 (stub)    = $(command -v vpython3 2>/dev/null)"
echo " GYP_GENERATORS      = $GYP_GENERATORS"

# Verify git is new enough
GIT_VER=$(git --version 2>/dev/null | awk '{print $3}')
GIT_OK=$(echo "$GIT_VER" | awk -F. '{exit !($1>2 || ($1==2 && $2>=29))}')
if [ "$GIT_OK" = "1" ]; then
    echo ""
    echo " ✓ git $GIT_VER is >= 2.29 (supports --object-format=sha1)"
else
    echo ""
    echo " ⚠ git $GIT_VER is < 2.29! Modern depot_tools needs --object-format=sha1"
    echo "   Fix: sudo add-apt-repository ppa:git-core/ppa && sudo apt update && sudo apt install git"
fi
echo ""
echo " Next step:"
echo "   cd $CHROMIUM_ROOT/src"
echo "   . build/android/envsetup.sh"
echo "   gyp_chromium   # wrapper function that forces python2.7 for GYP scripts"
echo "   ninja_run -C out/Release chrome_shell_apk   # forces python2.7 for ninja subprocess"
echo ""
echo " NOTE: gyp_chromium and ninja_run are wrapper functions defined in this env file."
echo "   They prepend python2_bin/ to PATH so subprocess 'python' calls use python2.7"
echo "   (Chromium 42 Python scripts are Python 2: grit.py, mojom_bindings_generator.py,"
echo "   java_cpp_enum.py, jinja_template.py, etc.)"
echo "==================================================================="
